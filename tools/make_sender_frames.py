"""
Generate firmware/sender/frames.h from a recorded BAKO CAN log.

The bench sender replays these frames with their original spacing, so the
receiver sees the same traffic pattern as the real vehicle.

Usage:
    python tools/make_sender_frames.py
    python tools/make_sender_frames.py --log data/raw/bms_log_car_Bako.txt --limit 500
"""

from __future__ import annotations
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.replay import read_log  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--log", type=Path, default=ROOT / "data/raw/bms_log_car_Bako.txt")
    ap.add_argument("--out", type=Path, default=ROOT / "firmware/sender/frames.h")
    ap.add_argument("--limit", type=int, default=0, help="keep only the first N frames (0 = all)")
    args = ap.parse_args(argv)

    frames = list(read_log(args.log))
    if args.limit:
        frames = frames[: args.limit]
    if not frames:
        print("No frames found in", args.log)
        return 1

    lines = [
        "// Generated by tools/make_sender_frames.py. Do not edit by hand.",
        f"// Source: {args.log.name}, {len(frames)} frames.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "  uint32_t dt_ms;    // delay since the previous frame",
        "  uint32_t id;       // 29-bit extended CAN identifier",
        "  uint8_t  dlc;",
        "  uint8_t  data[8];",
        "} BakoFrame;",
        "",
        "static const BakoFrame FRAMES[] = {",
    ]
    prev_ts = frames[0].ts_ms
    for fr in frames:
        dt = max(0, fr.ts_ms - prev_ts)
        prev_ts = fr.ts_ms
        data = list(fr.data[:8]) + [0] * (8 - len(fr.data[:8]))
        bytes_c = ",".join(f"0x{b:02X}" for b in data)
        lines.append(f"  {{{dt}, 0x{fr.can_id & 0x1FFFFFFF:08X}, {min(fr.dlc, 8)}, {{{bytes_c}}}}},")
    lines += [
        "};",
        "",
        f"static const uint32_t FRAME_COUNT = {len(frames)};",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    span_s = (frames[-1].ts_ms - frames[0].ts_ms) / 1000
    print(f"Wrote {len(frames)} frames ({span_s:.1f} s of traffic) to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
